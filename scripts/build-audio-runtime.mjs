import {build} from 'esbuild';
import {copyFile, mkdir, readFile, writeFile, readdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'assets/audio');
const modules = path.join(root, 'node_modules');
await mkdir(out, {recursive: true});
const pkg = async name => JSON.parse(await readFile(path.join(modules, name, 'package.json'), 'utf8'));
for (const name of ['@tensorflow/tfjs', '@tensorflow/tfjs-core', '@tensorflow/tfjs-converter', '@tensorflow/tfjs-backend-wasm']) {
  if ((await pkg(name)).version !== '4.22.0') throw new Error(`${name} must be pinned to 4.22.0.`);
}
if ((await pkg('@spotify/basic-pitch')).version !== '1.0.1') throw new Error('Basic Pitch must be pinned to 1.0.1.');

const result = await build({
  absWorkingDir: root,
  entryPoints: ['audio-runtime/worker.mjs'],
  outfile: 'assets/audio/audio-transcription-worker.js',
  bundle: true, minify: true, format: 'iife', platform: 'browser',
  target: ['es2020'], legalComments: 'linked', metafile: true,
  // Use the matching upstream ESM source for the browser; Node tests use CJS.
  alias: {'@spotify/basic-pitch/cjs/toMidi.js': '@spotify/basic-pitch/esm/toMidi.js'},
  banner: {js: '/* Generated by npm run build:audio. See THIRD_PARTY_NOTICES.txt. */'}
});
for (const file of ['model.json', 'group1-shard1of1.bin']) {
  await copyFile(path.join(modules, '@spotify/basic-pitch/model', file), path.join(out, file));
}
// Deliberately omit the threaded binary. The runtime explicitly disables threads
// and selects SIMD when supported, otherwise the baseline single-thread binary.
for (const file of ['tfjs-backend-wasm.wasm', 'tfjs-backend-wasm-simd.wasm']) {
  await copyFile(path.join(modules, '@tensorflow/tfjs-backend-wasm/dist', file), path.join(out, file));
}
const bundled = new Set(['@spotify/basic-pitch', '@tensorflow/tfjs-backend-wasm']);
for (const output of Object.values(result.metafile.outputs)) {
  for (const [input, detail] of Object.entries(output.inputs)) {
    if (!detail.bytesInOutput) continue;
    const match = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
    if (match) bundled.add(match[1]);
  }
}
const apache = await readFile(path.join(modules, '@spotify/basic-pitch/LICENSE'), 'utf8');
let notices = 'KeyMemory browser-local audio transcription\n\n' +
  'Generated reproducibly with npm ci && npm run build:audio. No runtime CDN requests.\n' +
  'Basic Pitch model and note decoding: Copyright 2022 Spotify AB (Apache-2.0).\n' +
  'TensorFlow.js / WASM: Copyright Google LLC (Apache-2.0).\n' +
  'Windowing adapted from Basic Pitch 1.0.1; changed to stream one window at a time,\n' +
  'dispose tensors explicitly, omit unused pitch bends, and cap input at 30 seconds.\n' +
  'Official sources: https://github.com/spotify/basic-pitch-ts and https://github.com/tensorflow/tfjs\n' +
  'Package versions/integrity are pinned by package-lock.json. Model files are copied unchanged.\n' +
  'The upstream Basic Pitch TFJS dependency is overridden to 4.22.0 to avoid duplicate registries.\n\n';
const versions = {};
for (const name of [...bundled].sort()) {
  const info = await pkg(name);
  versions[name] = info.version;
  const files = await readdir(path.join(modules, name));
  const license = files.find(file => /^licen[cs]e(?:\.md|\.txt)?$/i.test(file));
  if (!license && info.license !== 'Apache-2.0' && name !== 'seedrandom') throw new Error(`Missing license for ${name}.`);
  notices += `===== ${name} ${info.version} (${info.license}) =====\n\n`;
  if (license) notices += await readFile(path.join(modules, name, license), 'utf8');
  else if (name === 'seedrandom') {
    const readme = await readFile(path.join(modules, name, 'README.md'), 'utf8');
    notices += readme.slice(readme.indexOf('LICENSE (MIT)'));
    const alea = await readFile(path.join(modules, name, 'lib/alea.js'), 'utf8');
    notices += '\n' + alea.slice(0, alea.indexOf('(function('));
  } else notices += apache;
  notices += '\n\n';
}
// These pinned source licenses cover native libraries in the published WASM
// binaries. Sources/commits match TensorFlow.js tfjs-v4.22.0 WORKSPACE.
for (const name of (await readdir(path.join(root, 'scripts/licenses'))).sort()) {
  notices += '\n===== WASM third-party component =====\n\n';
  notices += await readFile(path.join(root, 'scripts/licenses', name), 'utf8');
}
await writeFile(path.join(out, 'THIRD_PARTY_NOTICES.txt'), notices);
const files = {};
for (const name of (await readdir(out)).sort()) {
  if (name === 'manifest.json') continue;
  const bytes = await readFile(path.join(out, name));
  files[name] = {bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex')};
}
await writeFile(path.join(out, 'manifest.json'), JSON.stringify({versions, files}, null, 2) + '\n');
console.log('Generated self-hosted audio runtime:', JSON.stringify(files, null, 2));
